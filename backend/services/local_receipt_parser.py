"""
Local OCR-based receipt parser module.

Provides a zero-network heuristic parser that extracts structured receipt information
directly from raw OCR text using regex and business rule heuristics when AI models
are exhausted or offline.
"""

import re
from datetime import datetime
from decimal import Decimal, InvalidOperation
from typing import Optional

from backend.schemas.receipt_schema import ReceiptExtraction, LineItem
from backend.utils.logger import get_logger

logger = get_logger(__name__)

# Exclusion keywords for line items (common header, footer, tax, payment terms)
SUMMARY_KEYWORDS = {
    "subtotal", "sub total", "sub-total", "tax", "sales tax", "tip", "gratuity",
    "total", "grand total", "balance due", "amount due", "net amount",
    "cash", "change", "visa", "mastercard", "amex", "debit", "credit",
    "payment", "approved", "auth", "table", "order", "server", "guest",
    "date", "time", "receipt", "tel", "phone", "fax", "thank", "welcome",
}

MONEY_REGEX = re.compile(r"\$?\s*([0-9]+\.[0-9]{2})\b")


def _clean_monetary_string(val: Optional[str]) -> Optional[str]:
    """Clean monetary string to numeric string or None."""
    if not val:
        return None
    cleaned = val.replace("$", "").replace(",", "").strip()
    try:
        Decimal(cleaned)
        return cleaned
    except InvalidOperation:
        return None


def parse_date(text: str) -> Optional[str]:
    """
    Attempt to extract an ISO format date (YYYY-MM-DD) from receipt text.
    Supports formats:
    - YYYY-MM-DD
    - MM/DD/YYYY or DD/MM/YYYY
    - Mon DD, YYYY (e.g. Feb 20, 2026 or 20 Feb 2026)
    """
    # 1. ISO format: 2026-02-20
    iso_match = re.search(r"\b(20[2-9][0-9])[-/.](0[1-9]|1[0-2])[-/.](0[1-9]|[12][0-9]|3[01])\b", text)
    if iso_match:
        y, m, d = iso_match.groups()
        return f"{y}-{m.zfill(2)}-{d.zfill(2)}"

    # 2. Textual month format: Feb 20, 2026 or February 20 2026
    month_pattern = r"(?:Jan(?:uary)?|Feb(?:ruary)?|Mar(?:ch)?|Apr(?:il)?|May|Jun(?:e)?|Jul(?:y)?|Aug(?:ust)?|Sep(?:tember)?|Oct(?:ober)?|Nov(?:ember)?|Dec(?:ember)?)"
    text_date_match = re.search(
        rf"\b({month_pattern})\s+([0-3]?[0-9])(?:st|nd|rd|th)?,?\s+(20[2-9][0-9])\b",
        text,
        re.IGNORECASE,
    )
    if text_date_match:
        month_str, day_str, year_str = text_date_match.groups()
        for fmt in ("%b %d %Y", "%B %d %Y"):
            try:
                dt = datetime.strptime(f"{month_str[:3].title()} {day_str} {year_str}", "%b %d %Y")
                return dt.strftime("%Y-%m-%d")
            except ValueError:
                pass

    # 3. Numeric slashed format: MM/DD/YYYY
    slash_match = re.search(r"\b(0?[1-9]|1[0-2])/(0?[1-9]|[12][0-9]|3[01])/(20[2-9][0-9])\b", text)
    if slash_match:
        m, d, y = slash_match.groups()
        return f"{y}-{m.zfill(2)}-{d.zfill(2)}"

    return None


def extract_merchant(lines: list[str]) -> Optional[str]:
    """Identify the likely merchant name from top receipt lines."""
    for line in lines[:5]:
        cleaned = line.strip()
        if not cleaned:
            continue
        # Skip pure numeric, phone, or generic greeting lines
        lowered = cleaned.lower()
        if any(skip in lowered for skip in ["order #", "table #", "tel", "phone", "date:", "time:"]):
            continue
        if re.search(r"^\d+$", cleaned):
            continue
        # If line contains letters and reasonable length, treat as merchant
        if any(c.isalpha() for c in cleaned) and len(cleaned) >= 3:
            return cleaned
    return None


def parse_receipt_text_locally(raw_text: str) -> ReceiptExtraction:
    """
    Parse unstructured OCR text into a structured ReceiptExtraction.

    Args:
        raw_text: Full raw text from EasyOCR.

    Returns:
        ReceiptExtraction populated with extracted fields and validation warnings.
    """
    warnings: list[str] = [
        "Structured data generated by Local OCR Fallback Parser (no AI model used)."
    ]

    if not raw_text or not raw_text.strip():
        warnings.append("OCR text was completely empty.")
        return ReceiptExtraction(warnings=warnings)

    lines = [line.strip() for line in raw_text.splitlines() if line.strip()]

    # 1. Merchant name
    merchant = extract_merchant(lines)
    if not merchant:
        warnings.append("Local parser could not determine merchant name.")

    # 2. Date
    date_val = parse_date(raw_text)
    if not date_val:
        warnings.append("Local parser could not parse receipt date.")

    # 3. Monetary amounts and line items
    subtotal: Optional[str] = None
    tax: Optional[str] = None
    tip: Optional[str] = None
    total_amount: Optional[str] = None
    line_items: list[LineItem] = []

    for line in lines:
        lower_line = line.lower()
        money_matches = MONEY_REGEX.findall(line)

        # Check for Subtotal
        if any(k in lower_line for k in ["subtotal", "sub total", "sub-total"]) and money_matches:
            subtotal = money_matches[-1]
            continue

        # Check for Tax
        if any(k in lower_line for k in ["tax", "sales tax", "vat", "gst"]) and money_matches:
            tax = money_matches[-1]
            continue

        # Check for Tip / Gratuity
        if any(k in lower_line for k in ["tip", "gratuity"]) and money_matches:
            tip = money_matches[-1]
            continue

        # Check for Total
        if any(k in lower_line for k in ["total", "grand total", "balance due", "amount due"]) and money_matches:
            # Prefer lines starting with or explicitly naming Total
            total_amount = money_matches[-1]
            continue

        # Candidate for Line Item
        # Must have a price and a description with letters that is not a summary line
        if money_matches:
            price_str = money_matches[-1]
            # Remove price from line to get item name
            item_name = MONEY_REGEX.sub("", line).replace("$", "").strip(" -:.")
            if item_name and len(item_name) >= 2 and any(c.isalpha() for c in item_name):
                # Ensure line is not a summary or payment term
                if not any(sk in item_name.lower() for sk in SUMMARY_KEYWORDS):
                    line_items.append(LineItem(item_name=item_name, price=price_str))

    # If total_amount was not found by keyword, fallback to highest price found in lower half
    if not total_amount:
        all_amounts = [Decimal(m) for m in MONEY_REGEX.findall(raw_text) if _clean_monetary_string(m)]
        if all_amounts:
            max_amount = max(all_amounts)
            total_amount = str(max_amount)
            warnings.append(
                f"Total amount not explicitly labeled; inferred highest amount {total_amount} as total."
            )
        else:
            warnings.append("Local parser could not find total amount.")

    extraction = ReceiptExtraction(
        merchant_name=merchant,
        date=date_val,
        line_items=line_items,
        subtotal=subtotal,
        tax=tax,
        tip=tip,
        total_amount=total_amount,
        warnings=warnings,
    )

    logger.info(
        f"Local OCR parser finished: merchant='{merchant}', date='{date_val}', "
        f"items={len(line_items)}, total={total_amount}"
    )
    return extraction

